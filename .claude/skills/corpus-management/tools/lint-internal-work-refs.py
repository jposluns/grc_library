#!/usr/bin/env python3
"""Internal work reference floor audit.

Counts, over the files git tracks in the scanned directories, the lines
that hold an internal work reference: a private work item, decision,
review, fix or ledger label of the kinds in ``PATTERNS``. The authored
scope is ``.claude/``; ``tools/`` and ``tests/`` at the repository root
are scanned only if present. The vendored AIQT snapshot (``.claude/aiqt/``
and ``.claude/rules/aiqt/``) is upstream-owned and left out. ``.web/`` and
``.github/`` are outside the scan, as the maintainer set it. A line counts
once however many patterns it matches; the per-kind totals count a line
under every kind it matches.

The count is compared with the pinned ``FLOOR`` by strict equality:

- a count above the floor fails, and every matching line is printed, since
  a whole-tree count cannot tell which of them a change added;
- a count below the floor fails too, until the change that removed
  references lowers ``FLOOR`` to the new count in the same change.

Lines that are functional fixture data for other gates count like any other
line: this is a pure count with no per-file allowance. The report names the
files holding most of the count.

What is scanned: the files ``git ls-files`` lists under the scanned
directories, not a walk of the filesystem, so a gitignored or untracked
machine-local file (a local settings file, the hook state directory) is not
counted and a maintainer machine counts what CI counts. Before listing,
the gate calls the repository's guard ``lint_common.require_own_git_dir``
on the root, so git variables in the environment that point git at
another repository, work tree or index (``GIT_INDEX_FILE`` naming a file
outside the git directory git reads, for one) make the gate exit 2. If
the listing cannot be read (git cannot run, the root is not in a work
tree, or git exits nonzero) or holds no tracked file under ``.claude/``
(an empty or missing index lists nothing), the gate exits 2 and reports
no count; it never falls back to walking the filesystem. Paths under ``__pycache__`` directories (generated bytecode,
not authored) and under the test scratch tree ``tests/tmp/`` at the root
are left out. Each file is decoded as UTF-8 with undecodable bytes replaced
and split on LF only.

RESIDUAL, stated (the same text the gate prints on every run):

    residual: a reference spelled outside these patterns, or split across
    lines, is not seen; a private item numbered 39.1, the Quebec privacy
    statute chapter, is not seen, nor is any private item written right
    after c. and a space (a statute chapter citation) or right after /acts/
    or /lois/ (a Justice Laws statute URL); a parenthesised letter and
    number right after delta gate, or a parenthesised D1 to D15 (the
    registered delta gate numbers, retired ones included), is not counted as
    a finding id, so a finding id written D1 to D15 is not seen; a bare
    worker (the worker, a worker, its worker) is not counted, since threads
    and processes use the same word, and an agent-sense worker form other
    than the listed ones is not seen; an orch- tool name or path is seen
    only in lower case; a work item id is counted only as 3b, then one to
    four decimal digits, then an optional suffix of lowercase letters and
    digits that begins with a letter g to z, ending at a word boundary,
    and not right after a # sign, so an id of five or more digits, an id
    whose suffix begins with a letter a to f, an id whose digits or suffix
    run straight into an uppercase letter or an underscore and an id
    written right after a # sign are not seen, nor is a hexadecimal hash
    or colour code of those shapes; a hexadecimal value that has the
    counted shape (3b and
    one to four decimal digits standing alone) is counted as a work item,
    and 3b and three digits before round or an ordinal is counted as a car
    round label even right after a # sign; a plural round
    count is seen only with a review, adversarial-QA, QA, fix, repair or
    verification qualifier, with at most one word between the number and the
    qualifier; container orchestration prose is told apart only by a
    preceding container, a plural or a following security or API, the
    generic multi-agent phrase that names one beside a peer and the vendored
    snapshot file name ending in mistakes-register are not counted, and
    other generic multi-agent prose is counted; a flip followed by to is not
    counted as a migration event; .web/ and .github/ are outside the scan,
    as the maintainer set it, so a reference there is not seen; a moved
    reference or an addition offset by an equal removal leaves the count
    unchanged; a backlog closure written as closing PR #N is not seen;
    generated data under the scanned directories is counted like authored
    text, so a regeneration can change the count

Fails closed: a git file listing that cannot be read, that the repository
guard refuses or that holds no tracked file under ``.claude/``, a listed
entry that is not a regular file (a symbolic link, a submodule, a FIFO, a socket, a
device) or a file that cannot be read (a tracked file missing from the work
tree included) makes the gate exit 2 naming each path; it never passes a
file it did not read.

usage: lint-internal-work-refs.py [--root DIR] [--floor N]

``--root`` overrides the repository root (the default is derived from this
file's location); ``--floor`` overrides the pinned ``FLOOR``. Both exist for
the regression tests, which point the gate at synthetic trees.

Exit codes:

    0   the count equals the floor.
    1   the count differs from the floor (above or below).
    2   cannot evaluate: the root or ``.claude/`` is not a real directory,
        the repository guard refuses the git environment, the git file
        listing cannot be read or holds no tracked file under ``.claude/``,
        or a scanned entry is not a regular file or cannot be read. Never a
        pass and never a count.
"""

from __future__ import annotations

import argparse
import os
import re
import stat
import subprocess
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent))
import lint_common  # noqa: E402  (this file's own tools directory)

REPO_ROOT = Path(__file__).resolve().parents[4]

# Whole-tree count pinned by strict equality. Lower it in the same change
# that removes references; never raise it.
FLOOR = 306

SCAN_DIRS = (".claude", "tools", "tests")
EXCLUDED_DIRS = (".claude/aiqt", ".claude/rules/aiqt", "tests/tmp")
PRUNED_NAMES = frozenset({"__pycache__"})
TOP_FILES = 5

# The patterns, one per kind: decision, review, private item, work item
# (one to four digits, not right after a # sign, with an optional suffix
# of lowercase letters and digits that begins with a letter g to z and
# ends at a word boundary), fix (an optional trailing letter), DONE and ledger
# ids; round, counted round, spelled round, QA round, car round and review
# leg labels; scripted fix labels; multi-agent references, agent-sense
# worker references and orch- tool names; migration events; lane
# references; finding ids in parentheses. Statute citations, Justice Laws
# statute URLs, delta gate labels, container orchestration prose and two
# generic multi-agent forms are left out (RESIDUAL states each). Adjacent
# string literals split entries so this file's own source holds no match.
PATTERNS = [
    ('decision id', r'\bD-[0-9]{3,5}\b'),
    ('review label RBQ', r'\bRBQ[0-9]+'),
    ('private item P-n.m', r'(?<!c\. )(?<!/acts/)(?<!/lois/)\bP-(?!39\.1(?![0-9]))[0-9]+\.[0-9]+'),
    ('work item 3bNNN', r'(?<!#)\b3b[0-9]{1,4}(?:[g-z][a-z0-9]*)?\b'),
    ('fix label FXn', r'\bFX[0-9]+[a-z]?'),
    ('DONE id', r'\bDONE:[0-9]+'),
    ('round label', r'(?i)\brounds?[- ][0-9]+[a-z]?\b'),
    ('counted round label', r'(?i)\b(?:two|three|four|five|six|seven|eight|nine|ten|[0-9]+)\s+(?:[a-z-]+\s+)?(?:review|adversarial-qa|qa|fix|repair|verification) rounds\b'),
    ('spelled round label', r'(?i)(?<![a-z])round[_ -](?:one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve)(?![a-z])'),
    ('orch' 'estrator reference', r'(?i)(?<!container )\borch' r'estrator(?!s\b)(?!\s+(?:security|api)\b)(?!-mistakes-register\b)(?!, a peer\b)'),
    ('orch' '- tool name', r'\borch' r'-[a-z]+'),
    ('worker reference', r'(?i)\b(?:expensive|second|another)\s+workers?\b|\bworker[- ](?:acquired|acquisition|provenance|prompt|exchange|attended|fan-out|tools?|detection)\b|\bmanage' r'-workers\b'),
    ('migration event', r'(?i)\b(?:before|after|until|since) the flip\b(?!\s+to\b)'),
    ('lane reference', r'(?i)\blane [0-9]\b'),
    ('ledger id', r'\b[A-Z0-9]+(?:-[A-Z0-9]+)+-1[01][0-9]{2}\b'),
    ('review leg label', r'(?i)\bvpr[0-9]+'),
    ('scripted fix label', r'(?i)\b(?:first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth|[0-9]+(?:st|nd|rd|th)) scripted fix\b'),
    ('QA round label', r'\bQA r[0-9]+\b'),
    ('finding id in parentheses', r'(?<![Dd]elta gate )\(\s*(?!D(?:[1-9]|1[0-5])\s*[,)])[A-Z][0-9]{1,2}\s*[,)]'),
    ('car round label', r'\b(?:E[0-9]+|3b[0-9]{3}) (?:round|first|second|third|fourth|fifth|sixth|seventh|eighth|ninth|tenth)\b'),
]
COMPILED = [(name, re.compile(rx)) for name, rx in PATTERNS]

RESIDUAL = ('residual: a reference spelled outside these patterns, or split'
            ' across lines, is not seen; a private item numbered 39.1, the '
            'Quebec privacy statute chapter, is not seen, nor is any '
            'private item written right after c. and a space (a statute '
            'chapter citation) or right after /acts/ or /lois/ (a Justice '
            'Laws statute URL); a parenthesised letter and number right '
            'after delta gate, or a parenthesised D1 to D15 (the registered'
            ' delta gate numbers, retired ones included), is not counted as'
            ' a finding id, so a finding id written D1 to D15 is not seen; '
            'a bare worker (the worker, a worker, its worker) is not '
            'counted, since threads and processes use the same word, and an'
            ' agent-sense worker form other than the listed ones is not '
            'seen; an orch- tool name or path is seen only in lower case; a'
            ' work item id is counted only as 3b, then one to four decimal '
            'digits, then an optional suffix of lowercase letters and '
            'digits that begins with a letter g to z, ending at a word '
            'boundary, and not right after a # sign, so an id of five or '
            'more digits, an id whose suffix begins with a letter a to f, '
            'an id whose digits or suffix run straight into an uppercase '
            'letter or an underscore and an id written right after a # '
            'sign are not seen, nor is a '
            'hexadecimal hash or colour code of those shapes; a hexadecimal '
            'value that has the counted shape (3b and one to four decimal '
            'digits standing alone) is counted as a work item, and 3b and '
            'three digits before round or an ordinal is counted as a car '
            'round label even right after a # sign; a plural round '
            'count is seen only with a review, adversarial-QA, QA, fix, '
            'repair or verification qualifier, with at most one word '
            'between the number and the qualifier; container orchestration '
            'prose is told apart only by a preceding container, a plural or'
            ' a following security or API, the generic multi-agent phrase '
            'that names one beside a peer and the vendored snapshot file '
            'name ending in mistakes-register are not counted, and other '
            'generic multi-agent prose is counted; a flip followed by to is'
            ' not counted as a migration event; .web/ and .github/ are '
            'outside the scan, as the maintainer set it, so a reference '
            'there is not seen; a moved reference or an addition offset by '
            'an equal removal leaves the count unchanged; a backlog closure '
            'written as closing PR #N is not seen; generated data under the'
            ' scanned directories is counted like authored text, so a '
            'regeneration can change the count')


def _is_excluded(rel: str) -> bool:
    return any(rel == d or rel.startswith(d + "/") for d in EXCLUDED_DIRS)


def _own_git_refusal(root: Path):
    """Return the repository guard's refusal for ``root``, or None.

    ``lint_common.require_own_git_dir`` refuses where git, under the
    inherited environment, would read a git directory, work tree or index
    other than ``root``'s own (``GIT_INDEX_FILE`` naming a file outside the
    git directory git reads included), so a redirected listing is never
    counted.
    """
    return lint_common.require_own_git_dir(root)


def _listing_refusal(listed):
    """Return why ``listed`` cannot be counted, or None.

    The check tests one thing: whether ``listed`` holds a path under
    ``.claude/``. A listing with none is taken as unreadable whatever the
    cause (an empty or missing index, an index that does not list this
    tree, or a tree tracked only under a root ``tools/`` or ``tests/``):
    counting it would report the lines in tracked files under a root
    ``tools/`` or ``tests/`` alone (0 only when there are none) and
    compare that with the floor as if it were the whole tree.
    """
    if any(name.startswith(".claude/") for name in listed):
        return None
    return ("git ls-files lists no tracked file under .claude/, so tracked "
            "files under a root tools/ or tests/ alone are not counted; no "
            "count is given")


def _tracked(root: Path):
    """Return (paths, error): the files git tracks under ``SCAN_DIRS``.

    ``paths`` is the sorted list of root-relative POSIX paths ``git
    ls-files`` reports, or None when the listing cannot be read, in which
    case ``error`` says why. There is no filesystem fallback.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--", *SCAN_DIRS],
            capture_output=True, check=False)
    except OSError as exc:
        return None, f"git ls-files could not run: {exc.strerror or exc}"
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", errors="replace").strip()
        return None, f"git ls-files exited {proc.returncode}: {detail}"
    names = proc.stdout.decode("utf-8", errors="surrogateescape").split("\0")
    return sorted({name for name in names if name}), None


def scan(root: Path):
    """Return (hits, unreadable, scanned) for the tracked files under ``root``.

    ``hits`` holds (path, line number, kinds, text) for every matching line;
    ``unreadable`` holds (path, reason) for every entry the gate could not
    read as a regular file, and for a git file listing it could not read,
    that the repository guard refused or that held no tracked file under
    ``.claude/``.
    """
    hits: list[tuple[str, int, list[str], str]] = []
    unreadable: list[tuple[str, str]] = []
    scanned = 0
    for top in SCAN_DIRS:
        base = root / top
        if top != ".claude" and not os.path.lexists(base):
            continue
        if os.path.islink(base) or not base.is_dir():
            unreadable.append((top, "not a real directory"))
    if unreadable:
        return hits, unreadable, scanned
    error = _own_git_refusal(root)
    if error is None:
        listed, error = _tracked(root)
        if listed is not None:
            error = _listing_refusal(listed)
    if error is not None:
        unreadable.append(("the git file listing", error))
        return hits, unreadable, scanned
    for rel in listed:
        if PRUNED_NAMES.intersection(rel.split("/")[:-1]) or _is_excluded(rel):
            continue
        full = os.path.join(root, rel)
        try:
            mode = os.lstat(full).st_mode
        except OSError as exc:
            unreadable.append((rel, exc.strerror or str(exc)))
            continue
        if not stat.S_ISREG(mode):
            unreadable.append((rel, "not a regular file"))
            continue
        try:
            with open(full, "rb") as fh:
                data = fh.read()
        except OSError as exc:
            unreadable.append((rel, exc.strerror or str(exc)))
            continue
        scanned += 1
        text = data.decode("utf-8", errors="replace")
        for number, line in enumerate(text.split("\n"), start=1):
            kinds = [n for n, c in COMPILED if c.search(line)]
            if kinds:
                hits.append((rel, number, kinds, line))
    return hits, unreadable, scanned


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="lint-internal-work-refs.py",
        description="Internal work reference floor audit (strict equality).")
    parser.add_argument("--root", default=None,
                        help="repository root to scan (default: this repository)")
    parser.add_argument("--floor", type=int, default=None,
                        help="override the pinned FLOOR (regression tests)")
    args = parser.parse_args(argv)
    root = Path(args.root) if args.root is not None else REPO_ROOT
    floor = FLOOR if args.floor is None else args.floor
    tag = "lint-internal-work-refs"

    if os.path.islink(root) or not root.is_dir():
        print(f"{tag}: cannot evaluate: root {root} is not a real directory "
              "(never a pass)", file=sys.stderr)
        return 2

    hits, unreadable, scanned = scan(root)
    if unreadable:
        for rel, reason in unreadable:
            print(f"{tag}: cannot read {rel}: {reason}", file=sys.stderr)
        print(f"{tag}: cannot evaluate: {len(unreadable)} entry(ies) not read "
              "(never a pass)", file=sys.stderr)
        return 2

    count = len(hits)
    print(f"{tag}: scanned {scanned} git-tracked file(s) under .claude/, and "
          "under root tools/ and tests/ where present "
          "(vendored AIQT snapshot .claude/aiqt/ and .claude/rules/aiqt/ left out; "
          ".web/ and .github/ are outside the scan)")
    per_kind = {name: 0 for name, _ in PATTERNS}
    per_file: dict[str, int] = {}
    for rel, _number, kinds, _text in hits:
        per_file[rel] = per_file.get(rel, 0) + 1
        for name in kinds:
            per_kind[name] += 1
    for name, _ in PATTERNS:
        print(f"  {name}: {per_kind[name]}")
    ranked = sorted(per_file.items(), key=lambda item: (-item[1], item[0]))
    if ranked:
        print(f"{tag}: files holding most of the count:")
        for rel, n in ranked[:TOP_FILES]:
            print(f"  {n} {rel}")
    print(f"{tag}: {RESIDUAL}")
    print(f"{tag}: count {count}, floor {floor}")

    if count == floor:
        print(f"{tag}: OK: the count equals the floor")
        return 0
    if count > floor:
        print(f"{tag}: FAIL: the count is {count - floor} above the floor; "
              "a whole-tree count cannot tell which lines are new, so every "
              "matching line follows:")
        for rel, number, kinds, text in hits:
            print(f"{rel}:{number}: {', '.join(kinds)} | {text.strip()[:160]}")
        return 1
    print(f"{tag}: FAIL: the count is {floor - count} below the floor; lower "
          f"FLOOR to {count} in this change")
    return 1


if __name__ == "__main__":
    sys.exit(main())
